SKIP_WORDS = ["濒危", "废碎", "废料", "回收", "旧", "二手", "零件", "代用品"]
norm = lambda s: re.sub(r"[（）()\s·・,，、/]", "", str(s or ""))


def pick(prefix, must):
    cand = [r for r in titems if r["hs"].startswith(prefix)]
    if must:
        cand = [r for r in cand if must in r["name"]]
    if not cand:
        return None
    good = [r for r in cand if not any(w in r["name"] for w in SKIP_WORDS)]
    pool = good or cand
    pool.sort(key=lambda r: (r["imPref"] <= 0, r["name"]))
    return pool[0]


