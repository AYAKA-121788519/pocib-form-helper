def auto_match(code, name):
    n = norm(name)
    if not n:
        return None
    for kw, prefix, must in KW:
        if kw in n:
            r = pick(prefix, must)
            if r:
                return r
    return None


rows = {}
src = {"override": 0, "auto": 0, "none": 0}
for code, name in PNAME.items():
    if code in OVERRIDE:
        hs = OVERRIDE[code]
        if hs is None:
            rows[code] = None
            src["none"] += 1
        else:
            r = BY_HS.get(hs)
            if not r:
                print("!! OVERRIDE 里的 %s 在税则中不存在，已置空：%s" % (code, hs))
                rows[code] = None
                src["none"] += 1
            else:
                rows[code] = r
                src["override"] += 1
        continue
    r = auto_match(code, name)
    if r:
        rows[code] = r
        src["auto"] += 1
    else:
        rows[code] = None
        src["none"] += 1

print("商品 %d：人工核定 %d，自动匹配 %d，待定 %d"
      % (len(PNAME), src["override"], src["auto"], src["none"]))
print("待定清单：")
for code, r in rows.items():
    if r is None:
        print("  ", code, PNAME[code])

# ---------- 生成 JS 常量 ----------
lines = []
for code in sorted(rows):
    r = rows[code]
    if r is None:
        lines.append('"%s":null' % code)
    else:
        lines.append('"%s":["%s",%g,%g,%g,%g]'
                     % (code, r["hs"], r["imPref"], r["vat"], r["rebate"], r["csVal"]))
js = "const GHS={" + ",\n".join(lines) + "};"

