"""补「索赔申请书」字段清单（POCIB 第 17 步：索赔）。

按官方填写说明：
  保单号码  = 货物运输保险单的号码
  受文者    = 国际保险公司（POCIB 固定）
  出口港    = 起运港中文名
  货物名称  = 货物中文名
  装载于    = 海运抄海运提单 Ocean Vessel Voy.No.；空运抄航空运单 Flight（等取回单据后填）
  损失金额  = 货物运输保险单上的「保险金额」
  随附单据  = 按需打○并填份数
  申请人    = 进口商中文名
  地址      = 进口商中文地址
  申请日期  = 日期格式
另外把表单正文拼成一整段，点一下就能整段复制。
"""
import io

P = "D:/pocib-helper/app/index.html"
s = io.open(P, encoding="utf-8", newline=None).read()
assert 'doc==="索赔申请书"' not in s, "已打过补丁"

anchor = '''    note="投保人与被保险人分开：投保人是去办保险的那一方（CIF/CIP 为出口商，FOB/CFR/FCA/CPT 为进口商），"
        +"被保险人固定填进口商——CIF 下出口商投保后把保单背书转让给进口商，索赔权在进口商手上。"
        +"起运地/目的地须带国家（如 HAMBURG, GERMANY）；CIF = (FOB + 运费) ÷ (1 − 加成率 × 费率)，保险费由 CIF 反推，不能用顺序公式。";
  }'''
assert anchor in s

block = anchor + '''
  // —— 索赔申请书（第 17 步：进口商持保单等单据向保险公司索赔）——
  else if(doc==="索赔申请书"){
    /* 申请人固定是进口商：CIF/CIP 下出口商投保后把保单背书转让，
       索赔权在进口商手上；FOB/CFR 下本来就是进口商自己投保，同理。 */
    const claimant=buyer;
    const portCn=portZh(c.port_load)||portShort(c.port_load);
    const goodsCn=c.hs_zh||(GD(c.goods_no)||{}).name_zh||c.goods;
    const sea=c.transport!=="空运";
    const amt="USD "+n2(D.insured);

    G("保单号码","（抄货物运输保险单右上角的保单号）","待确认");
    G("受文者","国际保险公司","固定");
    G("出口港（起运港，中文）",portCn,"自动");
    G("货物名称（中文）",goodsCn,"自动");
    G("装载于",sea
        ? "抄海运提单的 Ocean Vessel Voy.No.（船名 + 航次）"
        : "抄航空运单（AWB）的 Flight 栏位（航班号 + 日期）","待确认");
    G("损失金额及币别",amt+"（＝保单上的保险金额）","自动");
    G("随附单据 · 保险单正本 ORIGINAL POLICY","__ 份（打○）","待确认");
    G("随附单据 · 提单正反面 BILL OF LADING","__ 份（打○，空运改填航空运单）","待确认");
    G("随附单据 · 商业发票 COMMERCIAL INVOICE","__ 份（打○）","待确认");
    G("随附单据 · 装箱单 PACKING LIST","__ 份（打○）","待确认");
    G("随附单据 · 与运送人损失追偿往来函件","__ 份（有则打○）","待确认");
    G("随附单据 · 其他证明文件（索赔清单 / 报价单）","__ 份（有则打○）","待确认");
    G("加盖印章","（请加盖贵公司大小章）","待确认");
    G("申请人",claimant.name_zh||"（先在公司档案填中文全称）","自动");
    G("地址",claimant.address_zh||"（先在公司档案填中文地址）","自动");
    G("申请日期","____ 年 __ 月 __ 日（须为日期格式）","待确认");
    G("正文（点一下整段复制）",
      "本公司向贵公司投保之进出口货物发生损失，兹请予以理赔。\\n"
      +"一、本公司自 "+portCn+" 港，进出口 "+goodsCn+" 货物，装载于 ____ 轮，"
      +"因货物发生损失，请依保险契约的约定予以理赔。\\n"
      +"二、前项损失共计损失 "+amt+" 元经计算如后：","自动");
    note="申请人固定是进口商（保单已背书转让，索赔权在进口商手上），地址填进口商中文地址，"
        +"两者都取自「公司档案」的中文字段。\\n"
        +"「装载于」与「保单号码」要等 POCIB 生成单据之后才拿得到："
        +"船名航次见海运提单的 Ocean Vessel Voy.No.（空运见航空运单的 Flight），保单号见货物运输保险单右上角。\\n"
        +"「损失金额」按保单上的保险金额填（不是发票金额，也不是 CIF 价）。"
        +"随附单据按实际需要打○并填份数，通常六项各 1 份；索赔清单/报价单没有就不打○。\\n"
        +"同一步的「出险通知书」本工具未收录官方填写说明，按 POCIB 页面上的栏位自行填。";
  }'''

s = s.replace(anchor, block, 1)
io.open(P, "w", encoding="utf-8", newline=None).write(s)
print("已插入索赔申请书分支")
